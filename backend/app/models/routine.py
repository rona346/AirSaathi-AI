from datetime import datetime
from typing import List, Optional
from pydantic import BaseModel, Field


class ActivityTimeWindow(BaseModel):
    title: str = Field(..., description="Activity title (e.g., Morning Walk, School Drop-off)")
    recommended_time: str = Field(..., description="Recommended or optimal hour window (e.g., 11:30 AM - 01:00 PM)")
    status: str = Field(..., description="Recommended, Caution, Avoid, or Indoor Alternative")
    risk_level: str = Field(..., description="Low, Moderate, High, or Critical")
    advice: str = Field(..., description="Specific, actionable guidance for this activity")
    rationale: str = Field(..., description="Atmospheric and physiological rationale (e.g. inversion layer, PM2.5 deposition)")
    indoor_alternative: Optional[str] = Field(None, description="Indoor replacement if outdoor exposure is hazardous")
    precautions: List[str] = Field(default_factory=list, description="Specific precautions (e.g. N95 mask, eye drops, nasal rinse)")


class FamilyVulnerabilityInput(BaseModel):
    has_children: bool = Field(False, description="Presence of infants or children (< 12 yrs)")
    has_seniors: bool = Field(False, description="Presence of elderly family members (60+ yrs)")
    has_respiratory_condition: bool = Field(False, description="Family members with asthma, COPD, or bronchitis")
    is_pregnant: bool = Field(False, description="Presence of pregnant family members")


class RoutinePreferencesInput(BaseModel):
    wakes_up_early: bool = Field(True, description="Family prefers early morning activity")
    commutes_to_office: bool = Field(True, description="Family has daily office commuters")
    school_going_kids: bool = Field(True, description="Family has school-going children")
    exercises_daily: bool = Field(True, description="Family engages in daily physical exercise")
    preferred_exercise_type: str = Field("walk", description="walk, run, gym, yoga, or cycling")


class RoutinePlanRequest(BaseModel):
    station_id: str = Field("delhi-anand-vihar", description="Identifier of the monitoring station")
    language: str = Field("en", description="'en' for English or 'hi' for Hindi")
    family_profile: Optional[FamilyVulnerabilityInput] = None
    preferences: Optional[RoutinePreferencesInput] = None


class RoutinePlanResponse(BaseModel):
    station_id: str
    station_name: str
    city: str
    aqi: int
    category: str
    prominent_pollutant: str
    is_demo_data: bool
    data_source: str
    observed_at: datetime
    language: str
    ai_provider: str = Field(..., description="'google-gemini' or 'expert-rules-fallback'")
    ai_generated: bool = Field(..., description="True if generated by Gemini API; False if rule-based fallback")
    
    # Time-of-day chronological sections
    morning: List[ActivityTimeWindow] = Field(default_factory=list, description="Morning timeline (06:00 - 12:00)")
    afternoon: List[ActivityTimeWindow] = Field(default_factory=list, description="Afternoon timeline (12:00 - 17:00)")
    evening: List[ActivityTimeWindow] = Field(default_factory=list, description="Evening & night timeline (17:00 - 22:00)")

    # Specialized activity cards
    school_commute: ActivityTimeWindow
    office_commute: ActivityTimeWindow
    exercise_plan: ActivityTimeWindow
    chores_plan: ActivityTimeWindow

    # Family-specific precautions
    family_precautions: List[str] = Field(default_factory=list)
    
    # Medical and environmental disclaimer
    disclaimer: str
    generated_at: datetime
