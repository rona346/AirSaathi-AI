from datetime import datetime
from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, Field
from backend.app.core.utils import get_utc_now

from backend.app.models.indoor import HouseholdInput
from backend.app.models.routine import FamilyVulnerabilityInput


class ChatRole(str, Enum):
    USER = "user"
    ASSISTANT = "assistant"
    SYSTEM = "system"


class ChatMessage(BaseModel):
    role: ChatRole = Field(..., description="Message author role: user, assistant, or system")
    content: str = Field(..., min_length=1, max_length=1500, description="Message text content")
    timestamp: datetime = Field(default_factory=get_utc_now)


class ChatContextInfo(BaseModel):
    station_id: str
    station_name: str
    city: str
    aqi: int
    category: str
    prominent_pollutant: str
    is_demo_data: bool
    data_source: str
    observed_at: datetime


class ChatRequest(BaseModel):
    message: str = Field(..., min_length=1, max_length=1000, description="User's query")
    station_id: str = Field("delhi-anand-vihar", description="Target CPCB station ID")
    language: str = Field("en", description="'en' for English or 'hi' for Hindi")
    history: List[ChatMessage] = Field(default_factory=list, description="Prior conversational context (bounded to last 8 turns)")
    family_profile: Optional[FamilyVulnerabilityInput] = None
    household: Optional[HouseholdInput] = None


class ChatResponse(BaseModel):
    message: str = Field(..., description="Assistant's response text in markdown")
    language: str = Field(..., description="'en' or 'hi'")
    ai_provider: str = Field(..., description="'google-gemini' or 'expert-rules-fallback'")
    ai_generated: bool = Field(..., description="True if generated by Gemini API; False if fallback")
    context_used: ChatContextInfo
    suggested_followups: List[str] = Field(default_factory=list, description="Quick follow-up query suggestions")
    disclaimer: str
    timestamp: datetime = Field(default_factory=get_utc_now)
